// User configurable options for Cyprus Push-to-Hear
// CARE NOT TO OMIT THE INCLUDED SEMI-COLONS AT END OF EACH LINE!
// KEYBINDS SET IN GAME VIA: CONFIGURE > CONTROLS > CONFIGURE ADDONS

// Set the volume that SOUNDS will be suppressed to while Push-to-Hear is active.
// Allowed range:		0 (off)  - 1 (full volume)
// Suggested range: 	0.1 - 0.3
// Default supplied: 	0.2
CYP_PUSHTOHEAR_MINIMUM_VOLUME_SOUND = 0.3;

// Set the volume that MUSIC will be suppressed to while Push-to-Hear is active.
// Allowed range:		0 (off)  - 1 (full volume)
// Suggested range: 	0.1 - 0.3
// Default supplied: 	0.2
CYP_PUSHTOHEAR_MINIMUM_VOLUME_MUSIC = 0.3;

// Set the time it takes, in Seconds, to fade down volumes to the levels above.
// Also controls how long it takes the PtH active icon to fade in.
// Allowed range:		0 (instant) - X (x = a reasonable lenght :P)
// Suggested range: 	0.1 - 0.3
// Default supplied: 	0.5
CYP_PUSHTOHEAR_SUPPRESS_DURATION = 0.3;

// Set the time it takes, in Seconds, to restore volumes to their original levels.
// Also controls how long it takes the PtH active icon to fade out.
// Allowed range:		0 (instant) - X (x = a reasonable lenght :P)
// Suggested range: 	0.5 - 1
// Default supplied: 	1
CYP_PUSHTOHEAR_RESTORE_DURATION = 1;

// Enable use of mouse buttons to activate Push-to-Hear.
// Allowed values: 		0 to disable / 1 to enable
// Default supplied:	0 (i.e., do not use)
CYP_PUSHTOHEAR_USEMOUSEBUTTONS = 0;

// Define the mouse button you hold down to activate Push-to-Hear.
// Left, Right and Wheel buttons are usually 1,2,3 respectively.
// Allowed values:		1 - X,  (x = number of mouse buttons you have)
// Default supplied:	4 
CYP_PUSHTOHEAR_MOUSEBUTTON = 4;

// Define mouse button modifier keys to activate Push-to-Hear.
// You hold these down at same time as button, to allow more combos.
// Allowed values: 		0 to disable / 1 to enable
// Default supplied:	0 (i.e., do not use)
CYP_PUSHTOHEAR_MOUSEBUTTON_SHIFT = 0;
CYP_PUSHTOHEAR_MOUSEBUTTON_CTRL = 0;
CYP_PUSHTOHEAR_MOUSEBUTTON_ALT = 0;

